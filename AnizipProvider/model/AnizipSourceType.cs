namespace AnizipProvider.model;

/// <summary>
/// Represents the source type of an anime release.
/// </summary>
public enum AnizipSourceType
{
    /// <summary>
    /// Unknown source type.
    /// </summary>
    Unknown = 1,

    /// <summary>
    /// Unknown source type (uppercase alias).
    /// </summary>
    UNKNOWN = Unknown,

    /// <summary>
    /// Camcorder source.
    /// </summary>
    Camcorder = 2,

    /// <summary>
    /// Camcorder source (uppercase alias).
    /// </summary>
    CAMCORDER = Camcorder,

    /// <summary>
    /// Television source.
    /// </summary>
    Tv = 3,

    /// <summary>
    /// Television source (uppercase alias).
    /// </summary>
    TV = Tv,

    /// <summary>
    /// VHS source.
    /// </summary>
    Vhs = 4,

    /// <summary>
    /// VHS source (uppercase alias).
    /// </summary>
    VHS = Vhs,

    /// <summary>
    /// Digital television source.
    /// </summary>
    Dtv = 5,

    /// <summary>
    /// Digital television source (uppercase alias).
    /// </summary>
    DTV = Dtv,

    /// <summary>
    /// LaserDisc source.
    /// </summary>
    Ld = 6,

    /// <summary>
    /// LaserDisc source (uppercase alias).
    /// </summary>
    LD = Ld,

    /// <summary>
    /// DVD source.
    /// </summary>
    Dvd = 7,

    /// <summary>
    /// DVD source (uppercase alias).
    /// </summary>
    DVD = Dvd,

    /// <summary>
    /// Super VCD source.
    /// </summary>
    Svcd = 8,

    /// <summary>
    /// Super VCD source (uppercase alias).
    /// </summary>
    SVCD = Svcd,

    /// <summary>
    /// VCD source.
    /// </summary>
    Vcd = 9,

    /// <summary>
    /// VCD source (uppercase alias).
    /// </summary>
    VCD = Vcd,

    /// <summary>
    /// Hong Kong DVD source.
    /// </summary>
    Hkdvd = 10,

    /// <summary>
    /// Hong Kong DVD source (uppercase alias).
    /// </summary>
    HKDVD = Hkdvd,

    /// <summary>
    /// Web source.
    /// </summary>
    Www = 11,

    /// <summary>
    /// Web source (uppercase alias).
    /// </summary>
    WWW = Www,

    /// <summary>
    /// High Definition Television source.
    /// </summary>
    Hdtv = 14,

    /// <summary>
    /// High Definition Television source (uppercase alias).
    /// </summary>
    HDTV = Hdtv,

    /// <summary>
    /// High Definition DVD source.
    /// </summary>
    HdDvd = 15,

    /// <summary>
    /// High Definition DVD source (uppercase alias).
    /// </summary>
    HD_DVD = HdDvd,

    /// <summary>
    /// Blu-ray source.
    /// </summary>
    BluRay = 16,

    /// <summary>
    /// Blu-ray source (uppercase alias).
    /// </summary>
    BLU_RAY = BluRay,
}